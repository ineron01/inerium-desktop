local mainMod = "SUPER"
local function is_backup_session()
    local p = os.getenv("HYPR_PROFILE")
    if p and p ~= "" then
        return p == "backup"
    end
    local home = os.getenv("HOME") or ""
    local f = io.open(home .. "/.config/hypr/profile", "r")
    if f then
        local line = f:read("*l")
        f:close()
        if line and line:match("%S") then
            return line:gsub("%s+", "") == "backup"
        end
    end
    return false
end

local launchPrefix = is_backup_session() and "" or "uwsm app -- "

local function digitCode(d)
    return "code:" .. (d == 0 and 19 or (9 + d))
end

